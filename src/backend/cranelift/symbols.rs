//! The runtime functions generated code calls, by name, for the JIT's
//! symbol table.

/// The address of a runtime function, for the JIT's symbol table.
pub(super) fn runtime_symbol(name: &str) -> Option<*const u8> {
    use crate::runtime::stubs::*;
    macro_rules! syms {
        ($($f:ident),* $(,)?) => {
            match name {
                $(stringify!($f) => Some($f as *const u8),)*
                _ => None,
            }
        };
    }
    syms!(
        ot_alloc_object,
        ot_alloc_object_sized,
        ot_alloc_literal,
        ot_alloc_array,
        ot_alloc_string,
        ot_make_function,
        ot_make_closure,
        ot_get_prop,
        ot_set_prop,
        ot_get_index,
        ot_set_index,
        ot_delete_prop,
        ot_array_len,
        ot_array_push,
        ot_get_global,
        ot_typeof_global,
        ot_set_global,
        ot_call,
        ot_call_method,
        ot_intrinsic,
        ot_check_type,
        ot_register_global,
        ot_math_call,
        ot_get_prop_ic,
        ot_set_prop_ic,
        ot_call_method_ic,
        ot_array_spread,
        ot_object_spread,
        ot_add_any,
        ot_sub_any,
        ot_mul_any,
        ot_div_any,
        ot_mod_any,
        ot_pow,
        ot_neg,
        ot_bit_and,
        ot_bit_or,
        ot_bit_xor,
        ot_shl,
        ot_shr,
        ot_shr_u,
        ot_eq_strict,
        ot_eq_loose,
        ot_lt,
        ot_gt,
        ot_lte,
        ot_gte,
        ot_not,
        ot_truthy,
        ot_typeof,
        ot_to_boolean,
        ot_to_number,
        ot_runtime_exit,
        ot_throw,
        ot_take_exception,
        ot_rethrow,
        ot_report_uncaught,
        ot_construct,
        ot_construct_ic,
        ot_call_super,
        ot_get_super_prop,
        ot_instanceof,
        ot_get_private,
        ot_set_private,
        ot_to_str,
        ot_in,
        ot_stack_init,
        ot_stack_overflow,
        ot_async_start,
        ot_async_resolve,
        ot_async_reject,
        ot_async_enter,
        ot_await,
        ot_await_result,
        ot_run_microtasks,
        ot_run_event_loop,
        ot_trace,
        ot_rest_args,
    )
}
